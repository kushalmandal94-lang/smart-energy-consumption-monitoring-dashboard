const mongoose = require('mongoose');
const EnergyReading = require('../models/EnergyReading');
const Alert = require('../models/Alert');
const { offlineMeters } = require('./meterController');
const { logAction } = require('../utils/auditLogger');

// Singleton Simulation Engine State
const simulationState = {
  status: 'running', // 'running', 'paused', 'stopped'
  intervalMs: 5000,
  intervalId: null,
  isSimulated: true, // Explicit flag: SIMULATED IoT Telemetry (Not physical hardware)
  disclaimer: 'SIMULATION MODE ACTIVE: Data generated by VoltPulse IoT Telemetry Simulator',
  lastReadingTimestamp: new Date(),
  totalReadingsGenerated: 1480,
  anomaliesDetected: 3,
  recentReadings: [],
  recentAnomalies: [
    {
      id: 'anom-01',
      meterId: 'MTR-HQ-HVAC-02',
      type: 'power_surge',
      message: 'Sudden inrush spike detected: 48.6 kW exceeds 45.0 kW rating',
      timestamp: new Date(Date.now() - 3600000),
      severity: 'warning',
    },
    {
      id: 'anom-02',
      meterId: 'MTR-LOG-COLD-01',
      type: 'voltage_fluctuation',
      message: 'Voltage sag detected: 204.2 V below nominal 230 V (11.2% drop)',
      timestamp: new Date(Date.now() - 1800000),
      severity: 'critical',
    },
  ],
};

// Internal engine tick
const executeSimulationCycle = async (injectedAnomalyType = null) => {
  if (simulationState.status !== 'running' && !injectedAnomalyType) {
    return;
  }

  const meters = Array.from(offlineMeters.values());
  const now = new Date();
  simulationState.lastReadingTimestamp = now;

  const cycleReadings = [];

  for (const meter of meters) {
    if (meter.status !== 'online') continue;

    // Base power calculation with realistic time-of-day profile + jitter
    const hour = now.getHours();
    let timeFactor = 1.0;
    if (hour >= 8 && hour <= 18) timeFactor = 1.8; // daytime peak
    else if (hour >= 19 && hour <= 22) timeFactor = 1.3; // evening
    else timeFactor = 0.5; // night baseline

    const baseKW = (meter.powerRatingKW || 30) * 0.45 * timeFactor;
    const jitter = (Math.random() - 0.5) * (meter.powerRatingKW * 0.08);
    let powerKW = Math.max(1.5, +(baseKW + jitter).toFixed(2));
    let voltage = +(232 + (Math.random() - 0.5) * 6).toFixed(1);
    let powerFactor = +(0.93 + (Math.random() - 0.5) * 0.05).toFixed(2);
    let frequencyHz = +(60.0 + (Math.random() - 0.5) * 0.15).toFixed(2);
    let anomalyDetected = false;
    let anomalyReason = null;

    // Check if an anomaly should be injected for this meter
    if (injectedAnomalyType) {
      if (injectedAnomalyType === 'power_surge') {
        powerKW = +(meter.powerRatingKW * 1.35).toFixed(2);
        anomalyDetected = true;
        anomalyReason = `Overload surge: ${powerKW} kW exceeds rating of ${meter.powerRatingKW} kW`;
      } else if (injectedAnomalyType === 'voltage_drop') {
        voltage = 202.4;
        anomalyDetected = true;
        anomalyReason = 'Severe voltage sag: 202.4 V (-12% from 230V nominal)';
      } else if (injectedAnomalyType === 'frequency_drift') {
        frequencyHz = 57.8;
        anomalyDetected = true;
        anomalyReason = 'Grid frequency excursion: 57.8 Hz outside normal tolerance (59.5-60.5 Hz)';
      } else if (injectedAnomalyType === 'power_factor') {
        powerFactor = 0.72;
        anomalyDetected = true;
        anomalyReason = 'Poor power factor penalty: 0.72 indicates heavy inductive reactive load';
      }
    }

    const currentAmps = +((powerKW * 1000) / (voltage * powerFactor * 1.732)).toFixed(1);
    const incrementalKWh = +((powerKW * (simulationState.intervalMs / 3600000))).toFixed(4);

    meter.currentPowerKW = powerKW;
    meter.dailyConsumptionKWh = +(meter.dailyConsumptionKWh + incrementalKWh).toFixed(2);
    meter.voltage = voltage;
    meter.currentAmps = currentAmps;
    meter.powerFactor = powerFactor;
    meter.frequencyHz = frequencyHz;
    meter.lastCommunication = now;

    const readingRecord = {
      meterId: meter.meterId,
      name: meter.name,
      building: meter.building,
      location: meter.location,
      powerKW,
      voltage,
      currentAmps,
      powerFactor,
      frequencyHz,
      incrementalKWh,
      timestamp: now,
      isSimulated: true, // MANDATORY: distinguish simulated data
      anomalyDetected,
      anomalyReason,
    };

    cycleReadings.push(readingRecord);
    simulationState.totalReadingsGenerated += 1;

    // If anomaly triggered, save Alert
    if (anomalyDetected) {
      simulationState.anomaliesDetected += 1;
      const anomalyEntry = {
        id: `anom-${Date.now()}`,
        meterId: meter.meterId,
        type: injectedAnomalyType || 'telemetry_anomaly',
        message: anomalyReason,
        timestamp: now,
        severity: 'critical',
      };
      simulationState.recentAnomalies.unshift(anomalyEntry);
      if (simulationState.recentAnomalies.length > 20) {
        simulationState.recentAnomalies.pop();
      }

      // Persist to MongoDB Alert model if ready
      if (mongoose.connection.readyState === 1) {
        try {
          await Alert.create({
            title: `SIMULATED ANOMALY: ${meter.name}`,
            message: anomalyReason,
            severity: 'critical',
            type: 'power_surge',
            metricValue: powerKW,
            thresholdValue: meter.powerRatingKW,
            deviceName: meter.name,
            timestamp: now,
          });
        } catch (err) {
          console.warn('MongoDB alert insert deferred:', err.message);
        }
      }
    }
  }

  simulationState.recentReadings = cycleReadings;
  return cycleReadings;
};

// Start background cycle
const startEngineTimer = () => {
  if (simulationState.intervalId) clearInterval(simulationState.intervalId);
  simulationState.intervalId = setInterval(() => {
    executeSimulationCycle().catch((err) => console.warn('Simulation tick notice:', err.message));
  }, simulationState.intervalMs);
};

// Auto-start engine
startEngineTimer();

// @desc    Get current IoT simulation status and telemetry health
// @route   GET /api/iot-simulation/status
// @access  Private
const getSimulationStatus = async (req, res, next) => {
  try {
    const meters = Array.from(offlineMeters.values());
    const onlineMeters = meters.filter((m) => m.status === 'online').length;
    const offlineMetersCount = meters.length - onlineMeters;

    res.status(200).json({
      success: true,
      data: {
        status: simulationState.status,
        isSimulated: simulationState.isSimulated,
        disclaimer: simulationState.disclaimer,
        intervalMs: simulationState.intervalMs,
        lastReadingTimestamp: simulationState.lastReadingTimestamp,
        totalReadingsGenerated: simulationState.totalReadingsGenerated,
        anomaliesDetected: simulationState.anomaliesDetected,
        meters: {
          total: meters.length,
          online: onlineMeters,
          offline: offlineMetersCount,
        },
        recentReadings: simulationState.recentReadings,
        recentAnomalies: simulationState.recentAnomalies.slice(0, 5),
      },
    });
  } catch (error) {
    next(error);
  }
};

// @desc    Start / resume IoT telemetry simulation
// @route   POST /api/iot-simulation/start
// @access  Private (Admin, Facility Manager, Energy Analyst)
const startSimulation = async (req, res, next) => {
  try {
    simulationState.status = 'running';
    startEngineTimer();

    await logAction({
      userId: req.user._id,
      userName: req.user.name,
      userRole: req.user.role,
      action: 'IOT_SIMULATION_STARTED',
      entityType: 'simulation',
      entityId: 'sim-engine',
      building: 'All Buildings',
      details: { intervalMs: simulationState.intervalMs, isSimulated: true },
      ipAddress: req.ip,
    });

    res.status(200).json({
      success: true,
      message: 'IoT Telemetry Simulation started successfully.',
      status: simulationState.status,
    });
  } catch (error) {
    next(error);
  }
};

// @desc    Pause IoT telemetry simulation
// @route   POST /api/iot-simulation/pause
// @access  Private (Admin, Facility Manager, Energy Analyst)
const pauseSimulation = async (req, res, next) => {
  try {
    simulationState.status = 'paused';
    if (simulationState.intervalId) {
      clearInterval(simulationState.intervalId);
      simulationState.intervalId = null;
    }

    res.status(200).json({
      success: true,
      message: 'IoT Telemetry Simulation paused. Telemetry streams paused at last timestamp.',
      status: simulationState.status,
    });
  } catch (error) {
    next(error);
  }
};

// @desc    Stop IoT telemetry simulation
// @route   POST /api/iot-simulation/stop
// @access  Private (Admin, Facility Manager)
const stopSimulation = async (req, res, next) => {
  try {
    simulationState.status = 'stopped';
    if (simulationState.intervalId) {
      clearInterval(simulationState.intervalId);
      simulationState.intervalId = null;
    }

    res.status(200).json({
      success: true,
      message: 'IoT Telemetry Simulation stopped.',
      status: simulationState.status,
    });
  } catch (error) {
    next(error);
  }
};

// @desc    Manually trigger one telemetry pulse cycle immediately
// @route   POST /api/iot-simulation/pulse
// @access  Private
const triggerPulse = async (req, res, next) => {
  try {
    const cycleReadings = await executeSimulationCycle();
    res.status(200).json({
      success: true,
      message: 'Manual simulation pulse ingested successfully.',
      timestamp: simulationState.lastReadingTimestamp,
      readingsCount: cycleReadings?.length || 0,
      data: cycleReadings,
    });
  } catch (error) {
    next(error);
  }
};

// @desc    Inject an intentional abnormal condition for verification & testing
// @route   POST /api/iot-simulation/inject-anomaly
// @access  Private (Admin, Energy Analyst)
const injectAnomaly = async (req, res, next) => {
  try {
    const { anomalyType = 'power_surge' } = req.body;
    const cycleReadings = await executeSimulationCycle(anomalyType);

    await logAction({
      userId: req.user._id,
      userName: req.user.name,
      userRole: req.user.role,
      action: 'SIMULATION_ANOMALY_INJECTED',
      entityType: 'simulation',
      entityId: 'sim-engine',
      building: 'All Buildings',
      details: { anomalyType },
      ipAddress: req.ip,
    });

    res.status(200).json({
      success: true,
      message: `Simulated anomaly '${anomalyType}' injected successfully. Anomaly alert triggered.`,
      anomaliesCount: simulationState.anomaliesDetected,
      data: cycleReadings,
    });
  } catch (error) {
    next(error);
  }
};

module.exports = {
  getSimulationStatus,
  startSimulation,
  pauseSimulation,
  stopSimulation,
  triggerPulse,
  injectAnomaly,
  simulationState,
};

